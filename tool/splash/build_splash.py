"""Builds the QPortal splash.

Run from the repo root: python3 tool/splash/build_splash.py

Writes two things from assets/images/QPortal_logo_complete.svg:
  1. web/index.html, between the SPLASH markers: the runtime splash
     (video + static logo + hand-off script, from runtime.css / runtime.js).
  2. tool/splash/out/render.html: the full animated version (anim.css /
     anim.js), used by render_video.sh to render the video frame by frame.
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
read = lambda p: open(p).read()
SVG = read("assets/images/QPortal_logo_complete.svg")

# Video frame is 3x the logo width, logo centred (runtime.css relies on this).
VIDEO_W, VIDEO_H = 2560, 1440
LOGO_W = VIDEO_W / 3


def el(id_prefix):
    """Return the full element whose id starts with id_prefix."""
    i = SVG.index('id="%s' % id_prefix)
    start = SVG.rindex("<", 0, i)
    tag = re.match(r"<(\w+)", SVG[start:]).group(1)
    if tag in ("text", "g"):
        end = SVG.index("</%s>" % tag, start) + len(tag) + 3
    else:
        end = SVG.index("/>", start) + 2
    return SVG[start:end]


LAYERS = [
    ("orbit", ["path70-"]),
    ("globe", ["path152-"]),
    ("shield", ["path76-", "path9-"]),
    ("one", ["circle171-7-", "text176-"]),
    ("zero", ["circle171-8-", "text177-"]),
    ("chain", ["path175-36-", "g2-"]),
    ("lock", ["path175-3-", "path179-"]),
    ("word", ["text185-"]),
    ("sub", ["text196-"]),
]
layers = "".join(
    '<g class="qp-l" id="qp-%s">%s</g>' % (name, "".join(el(p) for p in ids))
    for name, ids in LAYERS
)
svg = ('<svg viewBox="0 0 95.597107 31.361395" xmlns="http://www.w3.org/2000/svg">'
       '<g transform="translate(206.63959,-143.66874)"><g transform="translate(-750.35835,783.69582)">'
       + layers + "</g></g></svg>")

# 1. Runtime splash in web/index.html
block = f"""<!-- SPLASH:START (generated by tool/splash/build_splash.py, do not edit) -->
<style>{read(HERE + '/runtime.css')}</style>
<div id="qp-splash" aria-hidden="true"><video id="qp-video" muted playsinline preload="auto"><source src="splash/qp_splash.webm" type="video/webm"><source src="splash/qp_splash.mp4" type="video/mp4"></video><div id="qp-logo">{svg}</div></div>
<script>{read(HERE + '/runtime.js')}</script>
<!-- SPLASH:END -->"""
html = read("web/index.html")
html = re.sub(r"<!-- SPLASH:START.*?<!-- SPLASH:END -->", lambda _: block, html, flags=re.S)
open("web/index.html", "w").write(html)

# 2. Render page: full animation, clocks frozen at #<ms> in the URL.
#    Black background so the runtime can drop it with mix-blend-mode: screen.
overrides = (
    "html,body,#qp-splash{background:#000!important}"
    f"#qp-logo{{width:{LOGO_W:.4f}px!important;margin-left:{-LOGO_W/2:.4f}px!important;"
    f"margin-top:{-LOGO_W*0.16403:.4f}px!important}}"
)
clock = ("<script>var __t=+location.hash.slice(1)||0,__p0=performance.now();"
         "performance.now=function(){return __p0};"
         "window.requestAnimationFrame=function(cb){return setTimeout(function(){cb(__p0+__t)},16)};</script>")
freeze = ("<script>setTimeout(function(){document.getAnimations().forEach("
          "function(a){a.pause();a.currentTime=__t})},50)</script>")
render = f"""<!doctype html><html><head><meta charset="utf-8"><style>{read(HERE + '/anim.css')}{overrides}</style></head><body>
{clock}<div id="qp-splash"><canvas id="qp-trails"></canvas><div id="qp-logo">{svg}</div></div>
<script>{read(HERE + '/anim.js')}</script>{freeze}</body></html>"""
os.makedirs(HERE + "/out", exist_ok=True)
open(HERE + "/out/render.html", "w").write(render)
print("index.html splash: %d bytes; render page written" % len(block))
